"""
Documentation Index Tool Handler.

Quick-lookup documentation index for the System Guide mode.
Returns a curated, hierarchical topic index rather than raw file listings.

Index data is loaded from data/.doc_index.json (relative to project root),
which is auto-generated by the RAG ingestion pipeline.  If the file is
missing or corrupt, the load error is propagated to the LLM so it can
understand why the index is unavailable.
"""

from __future__ import annotations

import json
import logging
from app.core.config import Paths
from typing import Any, Dict, List, Optional, Tuple

logger = logging.getLogger(__name__)

# ── Project Root ─────────────────────────────────────────────────────────────
# __file__ = backend/app/domain/tools/builtin/doc_index.py
# 6 levels up = project root
_PROJECT_ROOT = Paths.root


def _load_index_from_file() -> Tuple[Optional[Dict[str, Dict[str, Any]]], Optional[str]]:
    """
    Attempt to load the doc index from data/.doc_index.json.

    Returns:
        (topics_dict, None) if successful
        (None, error_message) if the file is missing or corrupt
    """
    json_path = _PROJECT_ROOT / "data" / ".doc_index.json"
    if not json_path.exists():
        msg = "File not found at data/.doc_index.json"
        logger.debug("doc_index JSON file not found at %s", json_path)
        return None, msg

    try:
        with open(json_path, "r", encoding="utf-8") as f:
            data = json.load(f)

        topics = data.get("topics")
        if not isinstance(topics, dict):
            msg = "Missing required 'topics' key or it's not a dict"
            logger.warning("doc_index JSON has no 'topics' key or it's not a dict, using fallback")
            return None, msg

        # Basic structural validation
        for slug, topic in topics.items():
            if not isinstance(topic, dict):
                msg = f"Topic '{slug}' is not a dict"
                logger.warning("doc_index: topic '%s' is not a dict, using fallback", slug)
                return None, msg
            if "title" not in topic or "description" not in topic or "subtopics" not in topic:
                msg = f"Topic '{slug}' is missing required fields (title, description, subtopics)"
                logger.warning("doc_index: topic '%s' missing required fields, using fallback", slug)
                return None, msg

        logger.info("Loaded doc index from %s (%d topics)", json_path, len(topics))
        return topics, None

    except json.JSONDecodeError as e:
        msg = f"JSON parse error: {e}"
        logger.error("Failed to parse doc_index JSON: %s, using hardcoded fallback", e)
        return None, msg
    except OSError as e:
        msg = f"IO error: {e}"
        logger.error("Failed to read doc_index JSON: %s, using hardcoded fallback", e)
        return None, msg


def _tokenize(text: str) -> List[str]:
    """
    Tokenize a string into individual words for multi-word search matching.

    Splits on whitespace and punctuation, filters to non-empty tokens.
    """
    import re
    return [t.lower() for t in re.split(r"[\s\-,.;:!?()\[\]{}'\"/]+", text) if t]


class DocIndexTool:
    """
    Documentation Index tool for quick topic lookup.

    Tags:
        - op:read
        - purpose:development
        - purpose:documentation
        - safe
        - text

    Operations:
        - List all topics when called without args
        - Filter by topic when topic arg is provided
        - Search across topic titles and descriptions
    """

    name = "Documentation Index"
    slug = "doc-index"
    capability = "doc-lookup"
    description = (
        "Quick lookup of available documentation topics by keyword. "
        "Returns a curated index of what topic areas exist. "
        "Use this for discovering what documentation topic areas or files exist "
        "(e.g., 'what docs are available?'). "
        "For answering conceptual questions about a topic, use doc-reader "
        "with semantic_search instead — it finds relevant content by meaning "
        "rather than by keyword match."
    )
    tags = [
        "op:read",
        "purpose:development",
        "purpose:documentation",
        "safe",
        "text",
    ]
    icon = "bookmark"
    color = "#28A745"  # Green

    config_schema = {
        "type": "object",
        "properties": {
            "max_results": {
                "type": "integer",
                "default": 30,
                "minimum": 1,
                "maximum": 100,
                "description": "Maximum number of results to return",
            },
        },
    }

    # Placeholder — topics list is populated dynamically in __init__
    arguments_schema = {
        "type": "object",
        "properties": {
            "topic": {
                "type": "string",
                "description": "Optional topic to filter by (e.g., 'architecture', 'database')",
            },
            "search": {
                "type": "string",
                "description": "Optional search term to find relevant docs across all topics",
            },
        },
        "required": [],
    }

    def __init__(self):
        # Load index from data/.doc_index.json — no hardcoded fallback.
        # If the file is missing or corrupt, the error is propagated to the LLM
        # via _source and _load_error fields in every response.
        index_data, error = _load_index_from_file()
        if index_data is not None:
            self._index = index_data
            self._source = "file"
            self._load_error = None
        else:
            self._index = {}
            self._source = "error"
            self._load_error = error or "Unknown error loading doc index"

        # Update the topic description in arguments_schema with current topic list
        self._update_topic_description()

    def _sort_topics(self, items):
        """Sort topics by display_order ASC, then slug ASC.

        ``items`` is an iterable of (slug, topic_info) tuples (as stored in
        ``self._index``).  Topics that lack a ``display_order`` key default
        to 999 so they sort to the end.
        """
        return sorted(
            items,
            key=lambda kv: (kv[1].get("display_order", 999), kv[0]),
        )

    def _update_topic_description(self) -> None:
        """Update the topic argument description with the current list of available topics."""
        topics_str = ", ".join(s for s, _ in self._sort_topics(self._index.items()))
        self.arguments_schema["properties"]["topic"]["description"] = (  # type: ignore[index]
            f"Optional topic to filter by (e.g., 'architecture', 'database', 'agents', 'workflows'). "
            f"Available topics: {topics_str}"
        )

    async def execute(self, config: Dict[str, Any], **kwargs) -> Dict[str, Any]:
        """
        Execute a documentation index lookup.

        Args:
            config: Tool configuration
            **kwargs: Tool arguments (topic, search)

        Returns:
            Dictionary with indexed documentation results
        """
        topic = kwargs.get("topic", "").strip().lower()
        search_term = kwargs.get("search", "").strip().lower()

        # Search mode — search across all topics
        if search_term and not topic:
            return self._search_index(search_term)

        # Topic filter mode
        if topic:
            return self._get_topic(topic, search_term)

        # No args — return full index overview
        return self._get_all_topics()

    def _get_all_topics(self) -> Dict[str, Any]:
        """Return the full topic tree."""
        topics = []
        for slug, info in self._sort_topics(self._index.items()):
            subtopic_count = len(info["subtopics"])
            paths = []
            for subtopic in info["subtopics"].values():
                paths.extend(subtopic["paths"])

            topics.append({
                "slug": slug,
                "title": info["title"],
                "description": info["description"],
                "subtopic_count": subtopic_count,
                "doc_count": len(set(paths)),
            })

        total_topics = len(topics)
        return {
            "success": True,
            "operation": "index",
            "total_topics": total_topics,
            "topics": topics,
            "source": self._source,
            "load_error": self._load_error,
            "usage_hint": "Use the 'topic' parameter to drill into a specific area, or 'search' to find specific docs.",
            "summary": f"Documentation index: {total_topics} topics available. Use 'topic' parameter to drill in.",
        }

    def _get_topic(self, topic: str, search_term: str = "") -> Dict[str, Any]:
        """Return details for a specific topic."""
        # Try exact match first
        if topic in self._index:
            info = self._index[topic]
        else:
            # Fuzzy match — find closest topic
            matches = [s for s in self._index if topic in s or s in topic]
            if not matches:
                available = ", ".join(s for s, _ in self._sort_topics(self._index.items()))
                return {
                    "success": False,
                    "error": f"Unknown topic: '{topic}'. Available topics: {available}",
                    "error_type": "NotFoundError",
                }
            info = self._index[matches[0]]
            topic = matches[0]

        # Tokenize search for multi-word matching within subtopics
        search_tokens = _tokenize(search_term) if search_term else []

        subtopics = []
        all_paths = []
        for subtopic_name, subtopic_info in info["subtopics"].items():
            if search_tokens:
                # Match if any search token appears in subtopic name, description, or paths
                sub_text = (subtopic_name + " " + subtopic_info["description"] + " " +
                           " ".join(subtopic_info["paths"])).lower()
                if not any(token in sub_text for token in search_tokens):
                    continue

            subtopics.append({
                "name": subtopic_name,
                "description": subtopic_info["description"],
                "paths": subtopic_info["paths"],
            })
            all_paths.extend(subtopic_info["paths"])

        total_docs = len(set(all_paths))
        return {
            "success": True,
            "operation": "topic",
            "topic": topic,
            "title": info["title"],
            "description": info["description"],
            "subtopics": subtopics,
            "total_docs": total_docs,
            "source": self._source,
            "load_error": self._load_error,
            "usage_hint": "Use doc-reader with path='<path>' to read a specific file.",
            "summary": f"Topic '{info['title']}': {len(subtopics)} subtopics, {total_docs} total docs",
        }

    def _search_index(self, search_term: str) -> Dict[str, Any]:
        """Search across all topics for a term, with multi-word tokenization support."""
        search_tokens = _tokenize(search_term)

        if not search_tokens:
            # Fall back to substring matching on the raw term for edge cases
            search_tokens = [search_term]

        results: List[Dict[str, Any]] = []

        for slug, info in self._index.items():
            # Build the full searchable text for this topic
            topic_text = (slug + " " + info["title"].lower() + " " + info["description"].lower())

            # Check if any token matches at the topic level
            topic_match = any(token in topic_text for token in search_tokens)

            matching_subtopics = []
            for sub_name, sub_info in info["subtopics"].items():
                sub_text = (sub_name.lower() + " " + sub_info["description"].lower() + " " +
                           " ".join(p.lower() for p in sub_info["paths"]))

                # Match if any search token is found in the subtopic text
                if any(token in sub_text for token in search_tokens):
                    # Filter paths to those that match (for relevance)
                    matched_paths = [p for p in sub_info["paths"]
                                     if any(token in p.lower() for token in search_tokens)]
                    matching_subtopics.append({
                        "name": sub_name,
                        "description": sub_info["description"],
                        "paths": matched_paths if matched_paths else sub_info["paths"],
                    })

            if topic_match or matching_subtopics:
                results.append({
                    "topic": slug,
                    "title": info["title"],
                    "description": info["description"],
                    "matched_subtopics": matching_subtopics if matching_subtopics else (
                        [{"name": s, "description": d["description"], "paths": d["paths"]}
                         for s, d in info["subtopics"].items()] if topic_match else []
                    ),
                })

        result_count = len(results)
        return {
            "success": True,
            "operation": "search",
            "search_term": search_term,
            "result_count": result_count,
            "results": results,
            "source": self._source,
            "load_error": self._load_error,
            "summary": f"Searched documentation index for '{search_term}' — found {result_count} matching topics",
        }
